/** Only send the selected pair; the full preset library never enters each request. */
export function anthologyWritingGuidance(draft: Pick<AnthologyDraft, 'genre' | 'style'>) {
  const genre = ANTHOLOGY_GENRES.find(g => g.id === draft.genre), style = ANTHOLOGY_STYLES.find(s => s.id === draft.style);
  if (!genre || !style) throw new Error('请选择有效的文体和笔触。');
  return { genre: { ...genre, instructions: GENRE_GUIDANCE[genre.id] }, style: { ...style, ...STYLE_GUIDANCE[style.id] } };
}
